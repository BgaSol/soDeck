import {readFile,writeFile} from 'node:fs/promises';
const type = s => s.anyOf ? s.anyOf.map(type).join(' | ') : s.$ref ? s.$ref.split('/').at(-1) : s.enum ? s.enum.map(v=>JSON.stringify(v)).join(' | ') : s.type==='array' ? `(${type(s.items)})[]` : s.type==='object' ? `{ ${Object.entries(s.properties??{}).map(([k,v])=>`${k}${s.required?.includes(k)?'':'?'}: ${type(v)}`).join('; ')} }` : ({integer:'number',number:'number',string:'string',boolean:'boolean',null:'null'})[s.type]??'unknown';
for(const name of ['state-feed','directory-context','pty-observe']) {
  const schema = JSON.parse(await readFile(new URL(`../contracts/${name}-v1.schema.json`,import.meta.url),'utf8'));
  for(const [prefix,file] of Object.entries(schema['x-imports']??{})) {
    const imported=JSON.parse(await readFile(new URL(`../contracts/${file}`,import.meta.url),'utf8'));
    const rename=value=>Array.isArray(value)?value.map(rename):value&&typeof value==='object'?Object.fromEntries(Object.entries(value).map(([key,v])=>[key,key==='$ref'?v.replace('#/$defs/',`#/$defs/${prefix}`):rename(v)])):value;
    for(const [key,value] of Object.entries(imported.$defs))schema.$defs[prefix+key]=rename(value);
  }
  delete schema['x-imports'];
  const content='// Generated by scripts/generate-communication.mjs; edit the schema.\nexport const schema = '+JSON.stringify(schema)+' as const;\n'+Object.entries(schema.$defs).map(([name,s])=>`export type ${name} = ${type(s)};`).join('\n')+'\n';
  const file=new URL(`../packages/sdk/src/${name}.generated.ts`,import.meta.url);
  if(process.argv.includes('--check')) {if(await readFile(file,'utf8').catch(()=>null)!==content)throw Error(`${name} contract is stale`);}
  else await writeFile(file,content);
  if(name==='state-feed') {
    const file=new URL('../crates/communication/src/state-feed.generated.json',import.meta.url),content=JSON.stringify(schema)+'\n';
    if(process.argv.includes('--check')){if(await readFile(file,'utf8').catch(()=>null)!==content)throw Error('Rust state contract is stale');}
    else await writeFile(file,content);
  }
}
