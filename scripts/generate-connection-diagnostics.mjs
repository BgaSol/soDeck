import { readFile, writeFile } from 'node:fs/promises';
{
const suffix = '';
const rustSuffix = '';
const schema = JSON.parse(await readFile(new URL(`../contracts/connection-diagnostics.schema.json`, import.meta.url), 'utf8'));
const type = s => s.anyOf ? s.anyOf.map(type).join(' | ') : s.$ref ? s.$ref.split('/').at(-1) : s.enum ? s.enum.map(v => JSON.stringify(v)).join(' | ') : s.type === 'array' ? `(${type(s.items)})[]` : s.type === 'object' ? `{ ${Object.entries(s.properties ?? {}).map(([k,v]) => `${k}${s.required?.includes(k)?'':'?'}: ${type(v)}`).join('; ')} }` : ({integer:'number',string:'string',boolean:'boolean',null:'null'})[s.type] ?? 'unknown';
const ts = '// Generated by scripts/generate-connection-diagnostics.mjs; edit the schema.\nexport const connectionDiagnosticsSchema = ' + JSON.stringify(schema) + ' as const;\n' + Object.entries(schema.$defs).map(([name,s]) => `export type ${name} = ${type(s)};`).join('\n') + '\n';
const rs = '// Generated by scripts/generate-connection-diagnostics.mjs; edit the schema.\n#![allow(dead_code)]\n' + Object.keys(schema.$defs).map(name => `pub type ${name} = serde_json::Value;`).join('\n') + '\n';
for (const [path,content] of [[`packages/sdk/src/connection-diagnostics${suffix}.generated.ts`,ts],[`crates/core/src/connection_diagnostics_contract${rustSuffix}.generated.rs`,rs]]) {
  const file = new URL('../'+path, import.meta.url);
  if(process.argv.includes('--check')) { if(await readFile(file,'utf8').catch(()=>null)!==content) throw Error(path+' is stale'); }
  else await writeFile(file,content);
}

}
