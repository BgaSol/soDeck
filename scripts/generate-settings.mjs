import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const descriptor=JSON.parse(await readFile(new URL('contracts/settings-descriptor-v1.schema.json',root),'utf8'));
const schema=JSON.parse(await readFile(new URL('contracts/settings-v1.schema.json',root),'utf8'));
Object.assign(schema.$defs,descriptor.$defs);
const type=s=>s.anyOf?s.anyOf.map(type).join(' | '):s.$ref?s.$ref.split('/').at(-1):s.enum?s.enum.map(v=>JSON.stringify(v)).join(' | '):s.type==='array'?`(${type(s.items)})[]`:s.type==='object'?`{ ${Object.entries(s.properties??{}).map(([k,v])=>`${JSON.stringify(k)}${s.required?.includes(k)?'':'?'}: ${type(v)}`).join('; ')} }`:({integer:'number',number:'number',boolean:'boolean',string:'string',null:'null'})[s.type]??'unknown';
for(const [path,content] of [
  ['packages/sdk/src/settings.generated.ts','// Generated by scripts/generate-settings.mjs; edit contracts/settings*.schema.json.\nexport const schema = '+JSON.stringify(schema)+' as const;\n'+Object.entries(schema.$defs).map(([name,s])=>`export type ${name} = ${type(s)};`).join('\n')+'\n'],
  ['contracts/settings.generated.json',JSON.stringify(schema)+'\n'],
]){
  const file=new URL(path,root);
  if(process.argv.includes('--check')){if(await readFile(file,'utf8').catch(()=>null)!==content)throw Error(`${path} is stale`);}
  else await writeFile(file,content);
}
