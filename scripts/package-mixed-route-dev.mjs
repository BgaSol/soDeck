// Build a fresh, isolated Windows directory package for T-027.
import { mkdir, readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { resolve, join, dirname, sep } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const output = resolve(process.argv[2] ?? join(root, `.local/dev/SoDeck-v2-T027-${Date.now()}`));
if (!output.startsWith(join(root, '.local/dev') + sep)) throw Error('Use a new isolated directory under .local/dev');

const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const hashes = {};
const artifacts = new Map();
async function put(target, bytes) {
  artifacts.set(target, bytes);
  hashes[target] = hash(bytes);
}
async function copy(source, target) { await put(target, await readFile(resolve(root, source))); }
function archiveManifest(archive) {
  for (let offset=0; offset+30<=archive.length&&archive.readUInt32LE(offset)===0x04034b50;) {
    const size=archive.readUInt32LE(offset+18), nameLength=archive.readUInt16LE(offset+26), extra=archive.readUInt16LE(offset+28);
    const start=offset+30+nameLength+extra, end=start+size;
    if(end>archive.length||archive.readUInt16LE(offset+8)!==0)throw Error('Expected stored ZIP generated by pack-plugin');
    if(archive.toString('utf8',offset+30,offset+30+nameLength)==='manifest.json')return JSON.parse(archive.subarray(start,end).toString());
    offset=end;
  }
  throw Error('Plugin manifest missing');
}

for (const name of ['sodeck-desktop.exe', 'sodeck-plugin-host.exe']) await copy(`target/debug/${name}`, name);
await put('portable.json', Buffer.from('{"schemaVersion":1}\n'));
await copy('resources/development-public-key.json', 'resources/development-public-key.json');
const plugins = [];
for (const name of ['terminal', 'files', 'network-proxy', 'monitor']) {
  const archive = await readFile(resolve(root, `.qa/t027/packages/${name}.sodeck-plugin`));
  await put(`resources/${name}.sodeck-plugin`, archive);
  const manifest = archiveManifest(archive);
  plugins.push({ pluginId: manifest.pluginId, path: `${name}.sodeck-plugin`, version: manifest.version, sha256: hash(archive) });
}
await put('resources/bundled-plugins.json', Buffer.from(JSON.stringify({ schemaVersion: 1, publicKeys: 'development-public-key.json', plugins: plugins.map(({ pluginId, path }) => ({ pluginId, path })) }, null, 2) + '\n'));
for (const name of ['graphite', 'soft-light', 'soft-dark', 'dopamine', 'catalog']) await copy(`themes/${name}.json`, `themes/${name}.json`);
for (const name of await readdir(join(root, 'assets/brand'))) {
  if (/^(pocket-deck.*\.(png|ico|svg)|manifest\.json)$/.test(name)) await copy(`assets/brand/${name}`, `assets/brand/${name}`);
}
for (const [dir, names] of [['ssh2', ['LICENSE-MIT', 'LICENSE-APACHE', 'SODECK-PATCH.md']], ['libssh2-sys', ['LICENSE-MIT', 'LICENSE-APACHE', 'libssh2/COPYING']], ['tauri-runtime-wry', ['LICENSE-MIT', 'LICENSE-APACHE-2.0']]]) {
  for (const name of names) await copy(`third-party/${dir}/${name}`, `licenses/${dir}/${name}`);
}
for (const [source, target] of [
  ['docs/tasks/T-027-results.md', 'evidence/validation.md'],
  ['docs/core/mixed-route.md', 'evidence/specification.md'],
  ['docs/technical/mixed-route-implementation.md', 'evidence/implementation.md'],
  ['docs/technical/connection-diagnostics.md', 'evidence/connection-diagnostics.md'],
  ['docs/design/connection-editor-refinement.md', 'evidence/connection-editor-refinement.md'],
  ['.qa/t027/native-latest.json', 'evidence/native-latest.json'],
  ['.qa/t027/diagnostics-native-latest.json', 'evidence/diagnostics-native-latest.json'],
  ['.qa/t027/visual-latest.json', 'evidence/visual-latest.json'],
]) await copy(source, target);
await put('Start-SoDeck.cmd', Buffer.from('@echo off\r\nsetlocal\r\nset "SODECK_DEV_MODE=0"\r\nstart "" "%~dp0sodeck-desktop.exe"\r\n'));
await put('README.md', Buffer.from(`# SoDeck ${JSON.parse(await readFile(join(root, 'apps/desktop/package.json'), 'utf8')).version} · T-027 连接诊断修订开发目录包\n\n双击 Start-SoDeck.cmd 启动。数据保存在本目录 data 下，与其他任务目录隔离。\n\n连接失败可查看每站、每阶段的成功和失败、未执行节点及安全错误详情，并复制报告。每个 SSH 节点合并身份与登录确认，四个独立插件统一接入；API/SDK6.1，core 数据库保持 v7，不增加诊断表或重建现有 v7 数据。诊断详情只在本次应用运行中保留。\n\n打包脚本本身不读取用户数据。若交付时另行复制现有 v7 配置，来源及验证见 evidence/validation.md；原目录保持可用。远端代理服务仍须在配置的端口正常监听。\n\n这是 Windows 开发验证包，不是安装器或正式发布。验证记录见 evidence/validation.md。\n`));
const git = args => execFileSync('git', ['-c', 'core.safecrlf=false', ...args], { cwd: root, windowsHide: true, maxBuffer: 128 * 1024 * 1024 });
const fingerprint = createHash('sha256').update(git(['diff', '--binary', 'HEAD']));
for (const path of git(['ls-files', '--others', '--exclude-standard', '-z']).toString().split('\0').filter(Boolean).sort()) { fingerprint.update(path + '\0'); fingerprint.update(await readFile(join(root, path))); }
const build = { deliveryTask: 'T027', packageRevision:'r8', version: JSON.parse(await readFile(join(root,'apps/desktop/package.json'),'utf8')).version, pluginApiVersion: '6.1.0', coreSchema: 7, profile: 'debug', release: false, sourceCommit: git(['rev-parse', 'HEAD']).toString().trim(), sourceDirty: true, sourceFingerprint: fingerprint.digest('hex'), plugins, hashes };
await mkdir(output);
for(const [target,bytes] of artifacts){await mkdir(dirname(join(output,target)),{recursive:true});await writeFile(join(output,target),bytes);}
await writeFile(join(output, 'build.json'), JSON.stringify(build, null, 2));
console.log(JSON.stringify({ output, files: Object.keys(hashes).length, desktopSha256: hashes['sodeck-desktop.exe'] }));
