import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const read=async path=>JSON.parse(await readFile(resolve(root,path),'utf8'));
export function validateTokens(value,keys,schema){
  if(!value||typeof value!=='object'||Object.keys(value).length!==keys.length)throw new Error('Token set must be complete');
  for(const key of Object.keys(value))if(!keys.includes(key))throw new Error(`Unknown token: ${key}`);
  for(const key of keys){
    const v=value[key],rule=schema[key];
    if(rule.type==='number'){if(typeof v!=='number'||!Number.isFinite(v)||v<rule.min||v>rule.max)throw new Error(`Invalid number: ${key}`);}
    else if(rule.type==='font'){if(typeof v!=='string'||!/^[-\w\s,"']+$/.test(v))throw new Error(`Invalid font: ${key}`);}
    else {const m=typeof v==='string'&&/^(\d+(?:\.\d+)?)(px|rem|ms)$/.exec(v);if(!m||!rule.units.includes(m[2])||Number(m[1])<rule.min||Number(m[1])>rule.max)throw new Error(`Invalid dimension: ${key}`);}
  }
}
export async function generate(readSource=read){
  const read=readSource;
  const schema=await read('packages/ui/src/tokens/schema.json'),foundation=await read('packages/ui/src/tokens/foundation.json'),catalog=await read('themes/catalog.json');
  validateTokens(foundation,schema.foundation,schema.properties);
  const profiles={},palettes={},surfaces={};const ids=new Set();
  for(const item of catalog.themes){
    if(!/^[a-z-]+$/.test(item.id)||ids.has(item.id)||item.file!==`${item.id}.json`||!['soft','dopamine'].includes(item.profile))throw new Error('Invalid theme catalog');ids.add(item.id);
    const palette=await read(`themes/${item.file}`);if(palette.id!==item.id||palette.mode!==item.mode||palette.schemaVersion!==2)throw new Error(`Catalog mismatch: ${item.id}`);
    profiles[item.profile]??=await read(`packages/ui/src/tokens/profiles/${item.profile}.json`);validateTokens(profiles[item.profile],schema.profile,schema.properties);
    const colors=await read(`themes/surfaces/${item.id}.json`),roles=['navigation','tool','successSurface','errorSurface','focusGap','capacityNormal','capacityWarning','capacityCritical','trafficSend','trafficReceive','trafficGap','trafficEvent'];
    if(Object.keys(colors).length!==roles.length||roles.some(role=>!(role in colors)))throw new Error(`Incomplete surface colors: ${item.id}`);
    for(const [role,v] of Object.entries(colors))if(typeof v!=='string'||!( /^#[\da-f]{6}([\da-f]{2})?$/i.test(v)||v.startsWith('$')&&v.slice(1) in palette.colors))throw new Error(`Invalid surface color: ${item.id}/${role}`);
    palettes[item.id]=palette;surfaces[item.id]=colors;
  }
  if(!ids.has(catalog.defaultThemeId)||!profiles.soft)throw new Error('Missing default theme or fallback profile');
  const variables=obj=>Object.entries(obj).map(([k,v])=>`  --sd-${k}: ${v};`).join('\n');
  let css='/* Generated by scripts/generate-ui-tokens.mjs. Do not edit. */\n:root, .sd-theme-scope {\n'+variables({...foundation,...profiles.soft})+'\n  --sd-navigation: var(--surface);\n  --sd-tool: var(--surface);\n  --sd-success-surface: var(--surface);\n  --sd-error-surface: var(--surface);\n  --sd-focus-gap: var(--canvas);\n  --sd-capacity-normal: var(--surface);\n  --sd-capacity-warning: var(--surface);\n  --sd-capacity-critical: var(--surface);\n}\n';
  const kebab=s=>s.replace(/[A-Z]/g,m=>'-'+m.toLowerCase());
  css+=':root, .sd-theme-scope {\n  --sd-traffic-send: var(--accent);\n  --sd-traffic-receive: var(--text);\n  --sd-traffic-gap: var(--secondary);\n  --sd-traffic-event: var(--warning);\n}\n';
  for(const item of catalog.themes){css+=`:where(:root, .sd-theme-scope)[data-theme="${item.id}"] {\n${variables(profiles[item.profile])}\n`;
    for(const [k,v] of Object.entries(surfaces[item.id]))css+=`  --sd-${kebab(k)}: ${v.startsWith('$')?`var(--${v.slice(1)})`:v};\n`;css+='}\n';}
  const ts='// Generated by scripts/generate-ui-tokens.mjs. Do not edit.\n'+`export const foundation = ${JSON.stringify(foundation,null,2)} as const;\nexport const themeCatalog = ${JSON.stringify(catalog,null,2)} as const;\nexport const themePalettes = ${JSON.stringify(palettes,null,2)} as const;\n`;
  return {'packages/ui/src/tokens/tokens.generated.css':css,'packages/ui/src/tokens/tokens.generated.ts':ts};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  for(const [path,content] of Object.entries(await generate())){
    if(process.argv.includes('--check')){if(await readFile(resolve(root,path),'utf8').catch(()=>null)!==content)throw new Error(`Stale generated UI tokens: ${path}`);}
    else await writeFile(resolve(root,path),content);
  }
  console.log('UI tokens and theme catalog validated.');
}
