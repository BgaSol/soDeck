const allNodes = visibleConnectionNodes(filterConnectionTree(buildConnectionTree(servers, servers, proxies), () => true));
assert.equal(allNodes.length, 10);
assert.equal(allNodes.filter(node => node.matched).length, 8);
assert.equal(allNodes.filter(node => node.record.id === 'jump').length, 2, 'A jump can occur under different prefixes');
assert.deepEqual(routeRecords(servers.find(record => record.id === 'edge'), servers, proxies).map(step => step.record.id), ['jump'], 'Referenced jump routes never expand recursively');
const filteredNodes = visibleConnectionNodes(filterConnectionTree(buildConnectionTree(servers, servers, proxies), record => ['生产环境', 'Web'].every(tag => record.tags.includes(tag))));
assert.deepEqual(filteredNodes.map(node => node.record.id), ['proxy', 'jump', 'zone', 'web']);
assert.deepEqual(filteredNodes.filter(node => node.matched).map(node => node.record.id), ['web'], 'Tags match targets only, never inherit to ancestors');
assert.throws(() => routeRecords({ route: [{ kind: 'ssh', serverId: 'missing' }] }, servers, proxies));

